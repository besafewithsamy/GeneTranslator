export const AMINO_NAMES: Record<Lang, Record<string, string>> = { en: AMINO_EN, fr: AMINO_FR };

export function aminoName(lang: Lang, abbr: string): string {
  if (abbr === 'Stop') return 'Stop';
  return AMINO_NAMES[lang][abbr] ?? abbr;
}
